	inline const char* get_name_sdl_macro_hints(const char* sdl_hint_macro) noexcept{
		auto arr = get_hints_table();
		const std::unordered_map<const char*,const char*> v(arr.begin(),arr.end(),arr.size());
		
		auto it = v.find(sdl_hint_macro);
		if (it != v.end()){
			return (*it).second;
		}else{
			return nullptr;
		}
	}

	template <typename LogT>
	void log_sdl_hints(LogT &&Log = SDL_Log){
		auto arr = get_hints_table();

		for (auto &&k : arr){
			Log("[log_sdl_hints] %s:%s",k.second,SDL_GetHint(k.first));
		}
	}

