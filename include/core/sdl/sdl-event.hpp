	template <typename LogT>
	void log_sdl_event(const SDL_Event &e, LogT &&Log = SDL_Log) noexcept{
		auto table = get_event_type_table();
		std::unordered_map<Uint32,const char*> v(table.begin(),table.end(),table.size());
		
		auto t = e.type;
		auto element = v.find(t);

		if (element != v.end()){
			do{
				if (start_with((*element).second,"SDL_EVENT_DISPLAY_")){
					Log("[log_sdl_event] %s displayID:%d",(*element).second,e.display.displayID);
					break;
				}

				if (start_with((*element).second,"SDL_EVENT_WINDOW_")){
					Log("[log_sdl_event] %s windowID:%d",(*element).second,e.window.windowID);
					break;
				}

				if (t == SDL_EVENT_KEYBOARD_ADDED || t == SDL_EVENT_KEYBOARD_REMOVED){
					Log("[log_sdl_event] %s keyboardID:%d",(*element).second,e.kdevice.which);
					break;
				}
				
				if (t == SDL_EVENT_KEY_DOWN || t == SDL_EVENT_KEY_UP){
					std::string s{};
					auto v = get_keymod_table();
					for(auto &&k :v){
						if (k.first & e.key.mod){
							if (!s.empty()){s += '|';}

							s += k.second;
						}
					}

					Log("[log_sdl_event] %s\t%s (%s) %s raw:%d windowID:%d keyboardID:%d",
						(*element).second,
						get_name_sdl_keycode(e.key.key),
						s.c_str(),
						get_name_sdl_scancode(e.key.scancode),
						e.key.raw,
						e.key.windowID,
						e.key.which
					);

					s.clear();
					break;
				}

				if (t == SDL_EVENT_TEXT_EDITING){
					Log("[log_sdl_event] %s start:%d len:%d text:%s windowID:%d",
						(*element).second,
						e.edit.start,e.edit.length,
						e.edit.text,
						e.edit.windowID
					);

					break;
				}

				if (t == SDL_EVENT_TEXT_EDITING_CANDIDATES){
					if(e.edit_candidates.candidates == nullptr)break;

					int count = 0;
					while(count < e.edit_candidates.num_candidates){
						Log("[log_sdl_event] %s candidates:%s num:%d select:%d windowID:%d (%s)",
							(*element).second,
							e.edit_candidates.candidates[count],
							count,
							e.edit_candidates.selected_candidate,
							e.edit_candidates.windowID,
							e.edit_candidates.horizontal?"horizontal":"vertical"
						);
						
						count++;
					}

					break;
				}
				
				if (t == SDL_EVENT_TEXT_INPUT){
					Log("[log_sdl_event] %s text:%s windowID:%d",
						(*element).second,
						e.text.text,
						e.text.windowID
					);

					break;
				}

				if (t == SDL_EVENT_MOUSE_ADDED || t == SDL_EVENT_MOUSE_REMOVED){
					Log("[log_sdl_event] %s mouseID:%d",
						(*element).second,
						e.mdevice.which
					);

					break;
				}

				if (t == SDL_EVENT_MOUSE_MOTION ){
					Log("[log_sdl_event]%s %s\tx:%f,y:%f xrel:%f,yrel:%f mouseID:%d,windowID:%d",
						(*element).second,
						get_name_sdl_mouse_button_flags(e.motion.state),
						e.motion.x,e.motion.y,
						e.motion.xrel,e.motion.yrel,
						e.motion.which,e.motion.windowID
					);
					
					break;
				}

				if (t == SDL_EVENT_MOUSE_BUTTON_DOWN || t == SDL_EVENT_MOUSE_BUTTON_UP){

					Log("[log_sdl_event]%s %s\tx:%f,y:%f clicks:%d down:%d mouseID:%d,windowID:%d",
						(*element).second,
						get_name_sdl_mouse_button_flags(e.button.button),
						e.button.x,e.button.y,
						e.button.clicks,e.button.down,
						e.button.which,e.button.windowID
					);

					break;
				}

				if (t == SDL_EVENT_MOUSE_WHEEL){

					Log(
						"[log_sdl_event]%s direction:%d x:%f,y:%f " //connect to
						"mouse_x:%f,mouse_y:%f int_x:%d,int_y:%d mouseID:%d,windowID:%d",
						(*element).second,
						e.wheel.direction,
						e.wheel.x,e.wheel.y,
						e.wheel.mouse_x,e.wheel.mouse_y,
						e.wheel.integer_x,e.wheel.integer_y,
						e.wheel.which,e.wheel.windowID
					);
					
					break;
				}

				if (t == SDL_EVENT_JOYSTICK_ADDED
				 || t == SDL_EVENT_JOYSTICK_REMOVED
				 || t == SDL_EVENT_JOYSTICK_UPDATE_COMPLETE){
					Log("[log_sdl_event] %s joystickID:%d",(*element).second,e.jdevice.which);
					break;
				}

				if (t == SDL_EVENT_JOYSTICK_AXIS_MOTION){
					Log("[log_sdl_event] %s axis:%d value:%d joystickID:%d",
						(*element).second,
						e.jaxis.axis,e.jaxis.value,
						e.jaxis.which);
					
					break;
				}

				if (t == SDL_EVENT_JOYSTICK_BALL_MOTION){
					Log(
						"[log_sdl_event]%s ball:%d xrel:%d,yrel:%d joystickID:%d",
						(*element).second,
						e.jball.ball,
						e.jball.xrel,e.jball.yrel,
						e.jball.which
					);

					break;
				}

				if (t == SDL_EVENT_JOYSTICK_HAT_MOTION){
					Log("[log_sdl_event]%s hat:%d value:%d joystickID:%d",
						(*element).second,
						e.jhat.hat,e.jhat.value,
						e.jhat.which
					);

					break;
				}

				if (t == SDL_EVENT_JOYSTICK_BUTTON_DOWN || t == SDL_EVENT_JOYSTICK_BUTTON_UP){
					Log("[log_sdl_event]%s button:%d down:%d joystickID:%d",
						(*element).second,
						e.jbutton.button,e.jbutton.down,
						e.jbutton.which
					);

					break;
				}

				if (t == SDL_EVENT_JOYSTICK_BATTERY_UPDATED){
					Log("[log_sdl_event]%s state:%s percent:%d joystickID:%d",
						(*element).second,
						get_name_sdl_power_state(e.jbattery.state),
						e.jbattery.percent,
						e.jbattery.which
					);

					break;
				}

				if (t == SDL_EVENT_GAMEPAD_ADDED
				 || t == SDL_EVENT_GAMEPAD_REMOVED
				 || t == SDL_EVENT_GAMEPAD_REMAPPED
				 || t == SDL_EVENT_GAMEPAD_UPDATE_COMPLETE
				 || t == SDL_EVENT_GAMEPAD_STEAM_HANDLE_UPDATED){
					Log("[log_sdl_event] %s joystickID:%d",
						(*element).second,e.gdevice.which);

					break;
				}

				if (t == SDL_EVENT_GAMEPAD_AXIS_MOTION){
					Log("[log_sdl_event] %s axis:%d value:%d joystickID:%d",
						(*element).second,
						e.gaxis.axis,e.gaxis.value,
						e.gaxis.which);
					
					break;
				}

				if (t == SDL_EVENT_GAMEPAD_BUTTON_DOWN || t == SDL_EVENT_GAMEPAD_BUTTON_UP){
					Log("[log_sdl_event]%s button:%d down:%d joystickID:%d",
						(*element).second,
						e.gbutton.button,e.gbutton.down,
						e.gbutton.which
					);

					break;
				}

				if (t == SDL_EVENT_GAMEPAD_TOUCHPAD_DOWN
				 || t == SDL_EVENT_GAMEPAD_TOUCHPAD_MOTION
				 || t == SDL_EVENT_GAMEPAD_TOUCHPAD_UP){

					Log("[log_sdl_event]%s touchpad:%d finger:%d x:%f,y:%f pressure:%f joystickID:%d",
						(*element).second,
						e.gtouchpad.touchpad,e.gtouchpad.finger,
						e.gtouchpad.x,e.gtouchpad.y,
						e.gtouchpad.pressure,
						e.gtouchpad.which
					);

					break;
				}

				if (t == SDL_EVENT_GAMEPAD_SENSOR_UPDATE ){
					Log("[log_sdl_event] %s sensor:%d data:%f,%f,%f joystickID:%d",
						(*element).second,
						e.gsensor.sensor,
						e.gsensor.data[0],
						e.gsensor.data[1],
						e.gsensor.data[2],
						e.gsensor.which
					);

					break;
				}

				if (t == SDL_EVENT_AUDIO_DEVICE_ADDED
				 || t == SDL_EVENT_AUDIO_DEVICE_REMOVED
				 || t == SDL_EVENT_AUDIO_DEVICE_FORMAT_CHANGED){

					Log("[log_sdl_event] %s recording:%d AudioDeviceID:%d",
					(*element).second,
					e.adevice.recording,
					e.adevice.which);

					break;
				}

				if (t == SDL_EVENT_CAMERA_DEVICE_ADDED
				 || t == SDL_EVENT_CAMERA_DEVICE_REMOVED
				 || t == SDL_EVENT_CAMERA_DEVICE_APPROVED
				 || t == SDL_EVENT_CAMERA_DEVICE_DENIED){

					Log("[log_sdl_event] %s CameraID:%d",
					(*element).second,
					e.cdevice.which);

					break;
				}

				if (t == SDL_EVENT_SENSOR_UPDATE){
					Log("[log_sdl_event] %s data:%f,%f,%f,%f,%f,%f SensorID:%d",
						(*element).second,
						e.sensor.data[0],
						e.sensor.data[1],
						e.sensor.data[2],
						e.sensor.data[3],
						e.sensor.data[4],
						e.sensor.data[5],
						e.sensor.which);

					break;
				}

				if (t >= SDL_EVENT_USER && t <= SDL_EVENT_LAST){
					Log("[log_sdl_event] %s windowID:%d code:%d",
						(*element).second,
						e.user.windowID,
						e.user.code
					);
					break;
				}

				if(t == SDL_EVENT_FINGER_DOWN
				 ||t == SDL_EVENT_FINGER_UP
				 ||t == SDL_EVENT_FINGER_MOTION
				 ||t == SDL_EVENT_FINGER_CANCELED){

					Log("[log_sdl_event] %s touchID:%ld fingerID:%ld "//connect to
						"x:%f,y:%f dx:%f,dy:%f pressure:%f windowID:%d",
						(*element).second,
						e.tfinger.touchID,
						e.tfinger.fingerID,
						e.tfinger.x,e.tfinger.y,
						e.tfinger.dx,e.tfinger.dy,
						e.tfinger.pressure,
						e.tfinger.windowID
					);

					break;
				}

				if (t == SDL_EVENT_PINCH_BEGIN
				 || t == ::SDL_EVENT_PINCH_UPDATE
				 || t == ::SDL_EVENT_PINCH_END){
					Log("[log_sdl_event] %s scale:%f windowID:%d",
						(*element).second,
						e.pinch.scale,
						e.pinch.windowID);

					break;
				}

				if (t == SDL_EVENT_PEN_PROXIMITY_IN
				 || t == SDL_EVENT_PEN_PROXIMITY_OUT){
					Log("[log_sdl_event] %s penID:%d windowID:%d",
						(*element).second,
						e.pproximity.which,
						e.pproximity.windowID);

					break;
				}

				if (t == SDL_EVENT_PEN_DOWN || t == SDL_EVENT_PEN_UP){

					Log("[log_sdl_event] %s pen_state:%s x:%f,y:%f eraser:%d down:%d penID:%d windowID:%d",
						(*element).second,
						get_name_sdl_pen_input_flags(e.ptouch.pen_state),
						e.ptouch.x,e.ptouch.y,
						e.ptouch.eraser,e.ptouch.down,
						e.ptouch.which,
						e.ptouch.windowID);

					break;
				}

				if (t == SDL_EVENT_PEN_MOTION){

					Log("[log_sdl_event] %s pen_state:%s x:%f,y:%f penID:%d windowID:%d",
						(*element).second,
						get_name_sdl_pen_input_flags(e.pmotion.pen_state),
						e.pmotion.x,e.pmotion.y,
						e.pmotion.which,
						e.pmotion.windowID);

					break;
				}

				if (t == SDL_EVENT_PEN_BUTTON_DOWN
				 || t == SDL_EVENT_PEN_BUTTON_UP){

					Log("[log_sdl_event] %s pen_state:%s x:%f,y:%f button:%d down:%d penID:%d windowID:%d",
						(*element).second,
						get_name_sdl_pen_input_flags(e.pbutton.pen_state),
						e.pbutton.x,e.pbutton.y,
						e.pbutton.button,e.pbutton.down,
						e.pbutton.which,
						e.pbutton.windowID);

					break;
				}

				if (t == SDL_EVENT_PEN_AXIS){
					
					Log("[log_sdl_event] %s pen_state:%s x:%f,y:%f axis:%s value:%f penID:%d windowID:%d",
						(*element).second,
						get_name_sdl_pen_input_flags(e.paxis.pen_state),
						e.paxis.x,e.paxis.y,
						get_name_sdl_pen_axis(e.paxis.axis),e.paxis.value,
						e.paxis.which,
						e.paxis.windowID);

					break;
				}

				if (t == SDL_EVENT_RENDER_TARGETS_RESET
				 || t == SDL_EVENT_RENDER_DEVICE_RESET
				 || t == SDL_EVENT_RENDER_DEVICE_LOST){

					Log("[log_sdl_event] %s windowID:%d",
						(*element).second,e.render.windowID);

					break;
				}

				if (t == SDL_EVENT_DROP_BEGIN
				 || t == SDL_EVENT_DROP_FILE
				 || t == SDL_EVENT_DROP_TEXT
				 || t == SDL_EVENT_DROP_COMPLETE
				 || t == SDL_EVENT_DROP_POSITION){
					Log("[log_sdl_event] %s x:%f,y:%f source:%s data:%s windowID:%d",
						(*element).second,
						e.drop.x,e.drop.y,
						e.drop.source,e.drop.data,
						e.drop.windowID);

					break;
				}

				if (t == SDL_EVENT_CLIPBOARD_UPDATE){
					if (e.clipboard.mime_types == nullptr) break;
					
					for(int count=0;count < e.clipboard.num_mime_types;count++){
						Log("[log_sdl_event] %s owner:%d mime_types:%s",
							(*element).second,
							e.clipboard.owner,
							e.clipboard.mime_types[count]);
					}

					break;
				}

				Log("[log_sdl_event] %s",(*element).second);

			}while(false);

		}else{
			Log("[log_sdl_event] (missing) %d",e.type);
		}

	}

	//provided by SDL, GetEventDescription
	template <typename LogT>
	void log_sdl_event_description(const SDL_Event &e, LogT &&Log = SDL_Log) noexcept{
		std::string buffer{};
		size_t size_need = SDL_GetEventDescription(&e,nullptr,0);
		buffer.resize(size_need+1);
		SDL_GetEventDescription(&e,buffer.data(),size_need);

		Log("[log_sdl_event_description] %s",buffer.c_str());
	}

	template<typename LogT>
	void log_sdl_mouse(LogT &&Log){
		if (!SDL_HasMouse())return;

		int count = 0;
		SDL_MouseID* m_ids = SDL_GetMice(&count);

		if (m_ids != nullptr){
			for (int i = 0;i < count; i++){
				Log("[log_sdl_mouse] %s",SDL_GetMouseNameForID(m_ids[i]));
			}
		}

		SDL_free(m_ids);
	}

	template<typename LogT>
	void log_sdl_mouse_state(LogT &&Log){
		if (!SDL_HasMouse())return;

		float x=0,y=0;
		float rx=0,ry=0;
		float gx=0,gy=0;
		SDL_MouseButtonFlags f=0,rf=0,gf=0;

		f = SDL_GetMouseState(&x,&y);
		rf = SDL_GetRelativeMouseState(&rx,&ry);
		gf = SDL_GetGlobalMouseState(&gx,&gy);

		Log("[log_sdl_mouse_state] f:%s x:%f,y:%f rf:%s rx:%f,ry:%f gf:%s gx:%f,gy:%f",
			core::get_name_sdl_mouse_button_flags(f),x,y,
			core::get_name_sdl_mouse_button_flags(rf),rx,ry,
			core::get_name_sdl_mouse_button_flags(gf),gx,gy
		);

	}

